package gen

// Panel route pin: the second half of the drift guard.
//
// buildModel only proves that a curated operation exists in the VENDORED spec.
// That spec is a hand-edited copy, so a route the panel moved or never had can
// live on in it: admin_list_users, admin_run_updates and list_forwarders all
// answered 404 on every panel that way. openapi/panel-routes.txt pins the
// operations the panel really serves. It is extracted from the panel's embedded
// spec (panel-api/internal/api/openapi.yaml), which the panel's
// TestOpenAPINoPhantomRoutes holds to its registered routes. CheckPanelRoutes
// fails for every curated operation missing from the pin.

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

var pathParamRe = regexp.MustCompile(`\{[^}/]+\}`)

// routeKey normalises "METHOD /path/{name}" to "METHOD /path/{}". Parameter
// names differ between the vendored spec ({id}) and the panel ({mbid}), but
// they do not change the URL a tool builds.
func routeKey(method, path string) string {
	return strings.ToUpper(method) + " " + pathParamRe.ReplaceAllString(path, "{}")
}

var httpMethods = map[string]bool{
	"get": true, "put": true, "post": true, "delete": true,
	"patch": true, "head": true, "options": true,
}

// PanelRoutes returns the sorted route keys of a panel OpenAPI spec. A path
// item with its own `servers` entry is mounted outside /api/v1 (for example
// /nic/update), so a tool cannot reach it at the API base URL; it is skipped.
func PanelRoutes(specPath string) ([]string, error) {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return nil, err
	}
	var s struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(raw, &s); err != nil {
		return nil, fmt.Errorf("parse panel spec: %w", err)
	}
	if len(s.Paths) == 0 {
		return nil, fmt.Errorf("panel spec %s: no paths", specPath)
	}
	var out []string
	for p, item := range s.Paths {
		if _, ok := item["servers"]; ok {
			continue
		}
		for m := range item {
			if httpMethods[m] {
				out = append(out, routeKey(m, p))
			}
		}
	}
	sort.Strings(out)
	return out, nil
}

// PanelRoutesFile renders the pin file: a provenance header, then one route key
// per line. source names the panel commit the spec was read from.
func PanelRoutesFile(routes []string, source string) []byte {
	var b bytes.Buffer
	b.WriteString("# Operations the jabali panel serves under /api/v1: one \"METHOD /path\" per\n")
	b.WriteString("# line, path parameters normalised to {}. Every op in tools.yaml and\n")
	b.WriteString("# admin-tools.yaml must appear here (internal/gen TestCuratedOpsArePanelRoutes).\n")
	b.WriteString("#\n")
	b.WriteString("# Generated by `make panel-routes` from panel-api/internal/api/openapi.yaml\n")
	fmt.Fprintf(&b, "# at jabali-panel %s. Do not edit by hand.\n", source)
	for _, r := range routes {
		b.WriteString(r)
		b.WriteByte('\n')
	}
	return b.Bytes()
}

func loadPanelRoutes(path string) (map[string]bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	routes := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		routes[line] = true
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(routes) == 0 {
		return nil, fmt.Errorf("%s: no routes", path)
	}
	return routes, nil
}

// CheckPanelRoutes returns an error naming every operation in the curation
// files that the pinned panel routes do not contain.
func CheckPanelRoutes(routesPath string, curationPaths ...string) error {
	routes, err := loadPanelRoutes(routesPath)
	if err != nil {
		return err
	}
	var missing []string
	for _, cp := range curationPaths {
		cur, err := loadCuration(cp)
		if err != nil {
			return err
		}
		for _, ct := range cur.Tools {
			parts := strings.Fields(ct.Op)
			if len(parts) != 2 {
				return fmt.Errorf("tool %q: op %q must be \"METHOD /path\"", ct.Name, ct.Op)
			}
			if !routes[routeKey(parts[0], parts[1])] {
				missing = append(missing, fmt.Sprintf("%s (%s)", ct.Op, ct.Name))
			}
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("curated ops the panel does not serve (they would 404): %s", strings.Join(missing, ", "))
	}
	return nil
}
