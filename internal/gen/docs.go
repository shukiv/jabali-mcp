package gen

// Documentation generator: emits docs/TOOLS.md from the same spec + curation
// the code generator consumes, so the reference cannot drift from the shipped
// surface. Hand-written composite tools are documented in compositeDocs below —
// TestDocsCoverEveryTool (internal/tools) fails if a registered tool is missing
// from the generated document.

import (
	"fmt"
	"strings"
)

// compositeDocs documents the hand-written tools (internal/tools/composite.go
// and issues.go). Keep in step when adding one; the coverage test enforces it.
const compositeDocs = `## Hand-written tools

Always registered alongside the generated read tools.

### diagnose_domain

One-call domain triage: config, SSL certificate status, DNS records, recent
nginx error-log lines, and bandwidth in a single JSON answer. A failed probe is
reported under ` + "`probe_errors`" + ` without failing the rest; an SSL 404 maps to
` + "`{\"status\": \"none\"}`" + ` (no certificate is a diagnosis, not an error).

| Argument | Type | Required | Description |
|---|---|---|---|
| ` + "`panel`" + ` | string | | target panel name for fleet mode; omit to use the default panel |
| ` + "`domain_id`" + ` | string | ✓ | the domain's ULID |
| ` + "`error_lines`" + ` | integer | | trailing nginx error-log lines to include (default 50, max 500) |

### report_issue

Draft or file a GitHub issue (bug report or feature request) on
[jabali-panel](https://github.com/shukiv/jabali-panel/issues) or
[jabali-mcp](https://github.com/shukiv/jabali-mcp/issues). In read-only mode it
only returns a prefilled ` + "`issues/new`" + ` link for the user to review and submit.
In write mode, direct creation via the ` + "`gh`" + ` CLI additionally requires
` + "`confirm: true`" + ` (it posts under the user's GitHub identity); ` + "`dry_run`" + ` previews.
Text containing panel/GitHub token patterns is refused. Set
` + "`diagnose_domain_id`" + ` to auto-attach the ` + "`diagnose_domain`" + ` probe results as
evidence.

| Argument | Type | Required | Description |
|---|---|---|---|
| ` + "`panel`" + ` | string | | target panel name for fleet mode; omit to use the default panel |
| ` + "`repo`" + ` | string | ✓ | one of: jabali-panel (panel/API behavior), jabali-mcp (MCP tool problems) |
| ` + "`kind`" + ` | string | ✓ | one of: bug, feature |
| ` + "`title`" + ` | string | ✓ | one-line issue title |
| ` + "`body`" + ` | string | ✓ | markdown body — never include tokens, passwords, or file contents |
| ` + "`diagnose_domain_id`" + ` | string | | domain ULID: attach diagnose_domain results (config, SSL, DNS, recent errors) |
| ` + "`confirm`" + ` | boolean | | create directly via gh (write mode only) |
| ` + "`dry_run`" + ` | boolean | | preview only |
`

// GenerateDocs renders the full tool reference as markdown.
func GenerateDocs(specPath, tenantCuration, adminCuration string) ([]byte, error) {
	spec, err := loadSpec(specPath)
	if err != nil {
		return nil, err
	}

	build := func(curationPath string) ([]toolModel, error) {
		cur, err := loadCuration(curationPath)
		if err != nil {
			return nil, err
		}
		models := make([]toolModel, 0, len(cur.Tools))
		for _, ct := range cur.Tools {
			m, err := buildModel(spec, ct)
			if err != nil {
				return nil, err
			}
			models = append(models, m)
		}
		return models, nil
	}

	tenant, err := build(tenantCuration)
	if err != nil {
		return nil, err
	}
	admin, err := build(adminCuration)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString(`# Tool reference

<!-- Generated by cmd/gen-tools -docs from openapi/openapi.yaml + the curation
     files. DO NOT EDIT — run 'make docs' after changing the tool surface. -->

Every tool takes an optional ` + "`panel`" + ` argument (fleet mode; omit for the default
panel). Write tools also take ` + "`dry_run`" + ` (preview the request without sending it),
and destructive tools act only when re-called with ` + "`confirm: true`" + `.

`)
	writeDocGroup(&b, "Read tools (always registered)", tenant, "read", false)
	writeDocGroup(&b, "Write tools (require `JABALI_MCP_ALLOW_WRITE=1`)", tenant, "write", false)
	writeDocGroup(&b, "Destructive tools (write + `confirm: true`)", tenant, "write", true)
	b.WriteString(compositeDocs)
	b.WriteString("\n")
	writeDocGroup(&b, "Admin tools (require `JABALI_MCP_ADMIN=1` + an admin token)", admin, "", false)
	return []byte(b.String()), nil
}

// writeDocGroup renders one section. group "" = all groups (admin file);
// destructive selects the confirm-gated subset of the write group.
func writeDocGroup(b *strings.Builder, title string, models []toolModel, group string, destructive bool) {
	fmt.Fprintf(b, "## %s\n\n", title)
	for _, m := range models {
		if group != "" && (m.Group != group || m.Destructive != destructive) {
			continue
		}
		fmt.Fprintf(b, "### %s\n\n%s\n\n`%s %s`\n\n", m.Name, m.Summary, m.Method, m.Path)
		fields := docFields(m)
		if len(fields) == 0 {
			continue
		}
		b.WriteString("| Argument | Type | Required | Description |\n|---|---|---|---|\n")
		for _, f := range fields {
			req := ""
			if f.Required {
				req = "✓"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", f.JSONName, docType(f), req, docDesc(f))
		}
		b.WriteString("\n")
	}
}

func docFields(m toolModel) []field {
	fields := append(append([]field{}, m.PathParams...), m.QueryParams...)
	if m.Paginated {
		fields = append(fields,
			field{JSONName: "page", GoType: "int", Desc: "page number (1-based)"},
			field{JSONName: "page_size", GoType: "int", Desc: "results per page"},
			field{JSONName: "q", GoType: "string", Desc: "search filter"},
		)
	}
	return append(fields, m.BodyFields...)
}

func docType(f field) string {
	switch f.GoType {
	case "int":
		return "integer"
	case "float64":
		return "number"
	case "bool", "*bool":
		return "boolean"
	default:
		return "string"
	}
}

func docDesc(f field) string {
	d := f.Desc
	var cons []string
	if len(f.Enum) > 0 {
		cons = append(cons, "one of: "+strings.Join(f.Enum, ", "))
	}
	if f.MinLen != nil {
		cons = append(cons, fmt.Sprintf("min length %d", *f.MinLen))
	}
	if f.Min != nil {
		cons = append(cons, fmt.Sprintf("min %d", *f.Min))
	}
	if f.Max != nil {
		cons = append(cons, fmt.Sprintf("max %d", *f.Max))
	}
	if len(cons) > 0 && !strings.Contains(d, cons[0]) {
		d += " (" + strings.Join(cons, "; ") + ")"
	}
	return strings.ReplaceAll(d, "|", "\\|")
}
